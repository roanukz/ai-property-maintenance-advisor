def test_quote_widened_to_the_code_printed_just_before_it() -> None:
    """Mutations: evidence_anchor_any_line (a code on an earlier line is used);
    evidence_anchor_gap_unbounded (a code far before the quote is used);
    evidence_anchor_token_unchecked (a code inside a longer token is used)."""
    from agent.rules.evidence import anchor_to_target

    quote = "Stands for sensor open. The heater stops until the sensor closes."
    widened = anchor_to_target(quote, TABLE_PAGE, target="E7")
    assert widened == "E7 | Stands for sensor open. The heater stops until the sensor closes."
    assert verify_span(widened, TABLE_PAGE, target="E7").ok
    # Already names the code: nothing to widen.
    assert anchor_to_target("E7 | Stands for sensor open.", TABLE_PAGE, target="E7") is None
    # Not verbatim in the page: never widened.
    assert anchor_to_target("Stands for sensor opened.", TABLE_PAGE, target="E7") is None
    # The code is on the line before the quote.
    assert anchor_to_target("Stands for high limit. The heater shuts off to protect the shell.",
                            TABLE_PAGE, target="E5") is None
    # The code is on the same line but further back than the allowed gap.
    assert anchor_to_target("Stands for low flow in the loop.", TABLE_PAGE, target="E3") is None
    # The nearest "E4" before the quote is inside "XE4"; the standalone E4 further back anchors it.
    assert anchor_to_target("Stands for a doubled label in one row.", TABLE_PAGE, target="E4") == \
        "E4 | XE4 label. Stands for a doubled label in one row."
    # The only "E9" before the quote is inside the longer token "XE9".
    assert anchor_to_target("Stands for a synthetic fault used to test token edges.",
                            TABLE_PAGE, target="E9") is None


