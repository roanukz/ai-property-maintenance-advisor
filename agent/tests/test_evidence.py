def test_edge_kept_only_with_verbatim_span(tmp_path: Path) -> None:
    """Mutation kg_rejected_edge_stored_unverified: try_add_edge stores a
    refused edge with verified=False instead of leaving it out."""
    g = KnowledgeGraph()
    series = g.add_family("Sundance Spas", "880 Series")
    flo = g.add_code("Sundance Spas", "880 Series", "FLO")
    good = "FLO: The heater senses no water flow."
    # The reason is checked too, so a span check that lets a span through is
    # not hidden by the later token check refusing it for another reason.
    cases = {
        "verbatim": (good, OK),
        "case_flipped": ("FLO: the heater senses no water flow.", NOT_IN_PAGE),
        "fuzzy_word": ("FLO: The heater detects no water flow.", NOT_IN_PAGE),
        "snippet_joined": ("FLO: The heater senses no water flow. [...] Rinse the filter", SNIPPET_JOINER),
        "no_target": ("The heater senses no water flow. Clean or replace", TARGET_MISSING),
        "too_short": ("FLO: The heater", TOO_SHORT),
    }
    for name, (evidence, reason) in cases.items():
        result = g.try_add_edge(HAS_CODE, series, flo, page_text=MANUAL, **edge_fields(evidence))
        assert (result.ok, result.reason) == (reason == OK, reason), name
    kept = g.edges()
    assert [e["evidence"] for e in kept] == [good]
    saved = tmp_path / "g.json"
    g.save(saved)
    text = saved.read_text(encoding="utf-8")
    assert "verified" not in text and "detects" not in text and "[...]" not in text
    assert len(json.loads(text)["edges"]) == 1


# Hypothesis page texts: words, the target, and every whitespace form 8.11 folds.
WORDS = st.sampled_from(["the", "heater", "Flow", "senses", "no", "water", "PUMP", "filter", "E10", "set",
                         "point.", "Clean", "cartridge,", "if", "clears", "(see", "page", "4)", "\u00e9t\u00e9"])
SPACES = st.sampled_from([" ", "  ", "\n", "\t", "\r\n", "\u00a0", " \n "])
TARGET = "FLO"


@st.composite
def page_and_span(draw):
    """A page with the target somewhere, and a raw substring of it that contains the target."""
    before = draw(st.lists(st.tuples(WORDS, SPACES), min_size=0, max_size=60))
    after = draw(st.lists(st.tuples(SPACES, WORDS), min_size=0, max_size=60))
    left = "".join(w + s for w, s in before)
    right = "".join(s + w for s, w in after)
    text = left + TARGET + right
    start = draw(st.integers(0, len(left)))
    end = draw(st.integers(len(left) + len(TARGET), len(text)))
    return text, text[start:end]


def _in_bounds(span: str) -> bool:
    return config.EVIDENCE_MIN_CHARS <= len(normalize_for_span(span)) <= config.EVIDENCE_MAX_CHARS


@settings(max_examples=300, deadline=None)
@given(data=page_and_span(), choice=st.data())
def test_evidence_span_property(data, choice) -> None:
    """Mutations evidence_match_casefold (spans compared case insensitively),
    evidence_normalize_casefolds, evidence_skip_joiner_check and
    evidence_skip_target_check: each lets a rejected span through."""
    text, span = data
    assume(_in_bounds(span))
    assert verify_span(span, text, target=TARGET) == verify_span(span, text, target=TARGET)
    assert verify_span(span, text, target=TARGET).ok, "a verbatim in bounds span with the target"
    norm_text, norm_span = normalize_for_span(text), normalize_for_span(span)

    # One non whitespace character changed.
    positions = [i for i, ch in enumerate(norm_span) if not ch.isspace()]
    i = choice.draw(st.sampled_from(positions))
    replacement = choice.draw(st.sampled_from("QXZqxz7#"))
    changed = norm_span[:i] + replacement + norm_span[i + 1:]
    assume(changed != norm_span and changed not in norm_text)
    assert not verify_span(changed, text, target=TARGET).ok

    # Case flipped on one cased character.
    cased = [i for i, ch in enumerate(norm_span) if ch.swapcase() != ch]
    j = choice.draw(st.sampled_from(cased))
    flipped = norm_span[:j] + norm_span[j].swapcase() + norm_span[j + 1:]
    assume(flipped not in norm_text)
    assert verify_span(flipped, text, target=TARGET).reason in (NOT_IN_PAGE, TARGET_MISSING)

    # Verbatim, but the page itself carries the snippet joiner inside the span.
    k = choice.draw(st.integers(0, len(norm_span)))
    joined_span = norm_span[:k] + " [...] " + norm_span[k:]
    joined_page = norm_text.replace(norm_span, joined_span, 1)
    if _in_bounds(joined_span) and TARGET in joined_span:
        assert verify_span(joined_span, joined_page, target=TARGET).reason == SNIPPET_JOINER

    # Found only in a snippet: the same words, but no raw text, or other raw text.
    assert verify_span(span, None, target=TARGET).reason == NO_PAGE_TEXT
    assert verify_span(span, "Synthetic page with other words entirely.", target=TARGET).reason == NOT_IN_PAGE

    # Missing the target: a span checked for a target it does not contain.
    assert verify_span(span, text, target="ZZTOP").reason == TARGET_MISSING


@settings(max_examples=200, deadline=None)
@given(start=st.integers(0, len(normalize_for_span(MANUAL))), length=st.integers(1, 460))
def test_evidence_span_bounds_on_a_fixture_page(start, length) -> None:
    """Mutation evidence_skip_length_check: condition 4 is not applied."""
    norm = normalize_for_span(MANUAL)
    span = norm[start:start + length].strip(" ")
    assume(TARGET in span)
    result = verify_span(span, MANUAL, target=TARGET)
    if len(span) < config.EVIDENCE_MIN_CHARS:
        assert result.reason == TOO_SHORT
    elif len(span) > config.EVIDENCE_MAX_CHARS:
        assert result.reason == TOO_LONG
    else:
        assert result.reason == OK


def _sentence_with(text: str, needle: str) -> str:
    for sentence in re.split(r"(?<=\.)\s+", text):
        if needle in sentence:
            return sentence
    raise AssertionError(f"no sentence with {needle!r}")


def test_quote_from_excerpt_verifies_when_snippet_formatting_differs(tmp_path: Path) -> None:
    """Mutation research_excerpts_from_snippet: build_sources cuts excerpts
    from the snippet (`content`) instead of `raw_content`."""
    ctx = RunContext(run_id="run-excerpt", mode="replay", ledger_path=tmp_path / "l.sqlite",
                     registry_path=tmp_path / "r.sqlite", graph_path=tmp_path / "g.json",
                     pages_dir=tmp_path / "pages")
    artifact = {"tool": "search", "results": [
        {"url": FLO_URL, "title": "Synthetic spa panel codes", "content": FLO_SNIPPET, "raw_content": FLO_RAW},
    ]}
    trail = [{"tool": "search", "query": "q", "n_results": 1, "credits": 1, "at": NOW, "status": "ok",
              "artifact": artifact, "pages": {}}]
    [source] = build_sources(ctx, [artifact], trail, set(),
                             excerpt_terms({"model": "Optima 880"}, "FLO", "hot tub not heating"))
    excerpt_quote = _sentence_with(" ".join(source["excerpts"]), "FLO")
    snippet_quote = _sentence_with(source["snippet"], "FLO")
    assert "**" in snippet_quote, "the snippet carries markdown the raw text lacks"
    assert verify_span(excerpt_quote, FLO_RAW, target="FLO").ok
    assert verify_span(snippet_quote, FLO_RAW, target="FLO").reason == NOT_IN_PAGE
    # The raw text was saved by its hash, so the page can be found again.
    assert (ctx.pages_dir / f"{source['text_sha256']}.txt").is_file()


def test_length_bounds_are_measured_after_normalization() -> None:
    """Mutation evidence_length_on_raw_span: condition 4 measures the raw span,
    so whitespace runs push a too short span over 20 characters and a 400
    character span over the limit.

    PLAN 8.11 condition 4 is read as measured on the normalized span.
    """
    short = "FLO: no water flow."  # 19 characters once normalized
    padded = short.replace(" ", "  \t ")
    assert len(normalize_for_span(padded)) == 19 and len(padded) > config.EVIDENCE_MIN_CHARS
    page = f"Synthetic page text. {padded} and more words after it."
    assert verify_span(padded, page, target=TARGET).reason == TOO_SHORT
    # Exactly the maximum once normalized, longer raw: it verifies.
    words = ["FLO"] + ["flow"] * 200
    norm = " ".join(words)[: config.EVIDENCE_MAX_CHARS].rstrip(" ")
    norm = norm + "x" * (config.EVIDENCE_MAX_CHARS - len(norm))
    raw = norm.replace(" ", " \n ")
    assert len(normalize_for_span(raw)) == config.EVIDENCE_MAX_CHARS < len(raw)
    long_page = f"Synthetic page text.\n{raw}\nEnd of the synthetic page."
    assert verify_span(raw, long_page, target=TARGET).reason == OK
    over = raw + "y"
    assert verify_span(over, long_page + over, target=TARGET).reason == TOO_LONG


